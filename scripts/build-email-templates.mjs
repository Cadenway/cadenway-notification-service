// Compiles the e-mail templates of src/modules/email/infrastructure/templates once, at build time:
// each <template>/html.mjml through MJML with strict validation, then the HTML, <template>/text.hbs
// and <template>/subject.hbs through the Handlebars precompiler. The result is one ES module,
// templates/generated/email-templates.js, that the running service loads with the Handlebars
// runtime only: the MJML compiler and the Handlebars compiler never run in the image
// (cw-email-templates).
//
// `pnpm build` runs it before `nest build`, which copies the generated module into dist/ (asset of
// nest-cli.json); `pnpm start:dev` runs it once before watching; Vitest runs it as a global setup,
// so the tests render the very templates the image ships. A template that fails the strict
// validation of MJML, or a Handlebars syntax error, fails the build.
//
// Every template is precompiled in strict mode with the built-in helpers only: a variable missing
// at render time throws instead of leaving an empty gap in the e-mail. The HTML part escapes its
// values; the subject and the text part are plain text and do not.
import { mkdir, readFile, readdir, rename, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import Handlebars from 'handlebars';
import mjmlCore from 'mjml-core';
import presetCore from 'mjml-preset-core';

const templatesDirectory = fileURLToPath(
  new URL('../src/modules/email/infrastructure/templates/', import.meta.url),
);
const outputDirectory = join(templatesDirectory, 'generated');
const outputFile = join(outputDirectory, 'email-templates.js');

// Folders of the templates directory that are not templates.
const notTemplates = new Set(['generated', 'partials']);

// `mjml-core` is a CommonJS module whose function is its default export.
const mjml2html = mjmlCore.default ?? mjmlCore;

/**
 * Precompiles one Handlebars source.
 *
 * @param {string} source - Template source.
 * @param {boolean} escape - Whether values are HTML-escaped (the HTML part only).
 * @returns {string} The JavaScript source of the template specification.
 */
function precompile(source, escape) {
  return Handlebars.precompile(source, {
    strict: true,
    knownHelpersOnly: true,
    noEscape: !escape,
  });
}

/**
 * Compiles the MJML of a template to HTML, with the core components and strict validation.
 *
 * @param {string} file - Path of the `html.mjml` file; its includes are resolved from it.
 * @returns {Promise<string>} The HTML, with its Handlebars placeholders untouched.
 */
async function compileMjml(file) {
  const { html } = await mjml2html(await readFile(file, 'utf8'), {
    validationLevel: 'strict',
    ignoreIncludes: false,
    filePath: file,
    includePath: templatesDirectory,
    presets: [presetCore],
    // No web font is loaded: the font stack of partials/head.mjml falls back on system fonts.
    fonts: {},
    keepComments: false,
    minify: false,
    beautify: false,
  });
  return html;
}

/**
 * Builds the generated module from every template folder.
 *
 * @returns {Promise<readonly string[]>} The names of the compiled templates.
 */
export async function buildEmailTemplates() {
  const entries = await readdir(templatesDirectory, { withFileTypes: true });
  const names = entries
    .filter((entry) => entry.isDirectory() && !notTemplates.has(entry.name))
    .map((entry) => entry.name)
    .sort();

  const compiled = [];
  for (const name of names) {
    const folder = join(templatesDirectory, name);
    const html = await compileMjml(join(folder, 'html.mjml'));
    const text = await readFile(join(folder, 'text.hbs'), 'utf8');
    const subject = (await readFile(join(folder, 'subject.hbs'), 'utf8')).trim();
    compiled.push(
      [
        `  ${JSON.stringify(name)}: {`,
        `    subject: ${precompile(subject, false)},`,
        `    html: ${precompile(html, true)},`,
        `    text: ${precompile(text, false)},`,
        '  },',
      ].join('\n'),
    );
  }

  const module = [
    '// Generated by scripts/build-email-templates.mjs from the templates of this folder: do not',
    '// edit, and do not commit. Loaded with the Handlebars runtime by handlebars-email-renderer.ts.',
    'export const emailTemplates = {',
    ...compiled,
    '};',
    '',
  ].join('\n');

  // Written next to its final name, then renamed: a reader never sees half a module.
  await mkdir(outputDirectory, { recursive: true });
  const temporary = `${outputFile}.${String(process.pid)}.tmp`;
  await writeFile(temporary, module, 'utf8');
  await rename(temporary, outputFile);
  return names;
}

/**
 * Global setup of Vitest: compiles the templates once before the test files run.
 *
 * @returns {Promise<void>} Settles once the module is written.
 */
export async function setup() {
  await buildEmailTemplates();
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const names = await buildEmailTemplates();
  console.log(`E-mail templates compiled: ${names.join(', ')}.`);
}
